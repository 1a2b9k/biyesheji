<#
    setup_git_trust.ps1 - let git trust the local accelerator's root CA.

    NOTE: this script is intentionally ASCII-only.
          Windows PowerShell 5.1 reads .ps1 files as ANSI/GBK when there is no BOM,
          so non-ASCII characters in a UTF-8 script turn into mojibake and can even
          break parsing. Keep .ps1 files ASCII-only.

    Background (measured on this machine):
      The hosts file pins github.com / api.github.com and 9 more domains to 127.0.0.1.
      Watt Toolkit (formerly Steam++) acts as a local reverse proxy and re-signs the
      TLS certificate with its own self-signed root CA, which is installed in the
      Windows certificate store. Python and browsers trust it, but git's openssl
      backend only uses its bundled ca-bundle.crt, so git fails with:
          SSL certificate problem: unable to get local issuer certificate (20)

    What this script does:
      1. Exports that root CA from the Windows store to .git-trust/tool-root-ca.pem
      2. Points THIS repository at that PEM for github.com domains only.
         Other hosts (e.g. gitee.com) keep using git's default CA bundle, so their
         verification strength is unchanged.

    Usage:
      powershell -File tools\setup_git_trust.ps1
      Re-run it if the accelerator rotates its certificate.
#>

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$outDir = Join-Path $repoRoot '.git-trust'
$pemPath = Join-Path $outDir 'tool-root-ca.pem'

New-Item -ItemType Directory -Force -Path $outDir | Out-Null

Write-Output '=== Export accelerator root CA from the Windows certificate store ==='
$certs = @(
    Get-ChildItem Cert:\LocalMachine\Root -ErrorAction SilentlyContinue |
        Where-Object { $_.Subject -match 'SteamTools|BeyondDimension' }
)
if ($certs.Count -eq 0) {
    Write-Output '  No SteamTools/BeyondDimension root CA found.'
    Write-Output '  If you are not using an accelerator, this script is not needed.'
    exit 1
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Generated by tools/setup_git_trust.ps1 - do not edit by hand.')
[void]$sb.AppendLine('# Source: Windows certificate store (LocalMachine\Root)')
foreach ($c in $certs) {
    Write-Output ('  {0}  (expires {1})' -f $c.Subject, $c.NotAfter)
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('# ' + $c.Subject + '  expires ' + $c.NotAfter)
    [void]$sb.AppendLine('-----BEGIN CERTIFICATE-----')
    [void]$sb.AppendLine([Convert]::ToBase64String($c.RawData, 'InsertLineBreaks'))
    [void]$sb.AppendLine('-----END CERTIFICATE-----')
}
[System.IO.File]::WriteAllText($pemPath, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Output ("  wrote: {0} ({1} bytes)" -f $pemPath, (Get-Item $pemPath).Length)

Write-Output '=== Configure this repo to use that CA for github domains only ==='
$domains = 'github.com', 'api.github.com', 'codeload.github.com', 'raw.githubusercontent.com', 'objects.githubusercontent.com'
foreach ($d in $domains) {
    git -C $repoRoot config --local "http.https://$d/.sslCAInfo" $pemPath
    Write-Output "  http.https://$d/.sslCAInfo"
}

Write-Output '=== Ensure the openssl backend is used ==='
Write-Output '  (schannel cannot acquire credentials inside the DSH sandbox)'
git -C $repoRoot config --local http.sslBackend openssl
Write-Output '  http.sslBackend = openssl'

Write-Output ''
Write-Output 'Done. Verify with: git ls-remote origin'
